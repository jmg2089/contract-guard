"""계약서에서 분석에 필요 없는 민감정보를 가린다.

왜 필요한가.

근로계약서에는 판정에 전혀 쓰이지 않는 개인정보가 들어 있다.
주민등록번호, 계좌번호, 전화번호, 주소, 이메일이 그렇다.
위약금 조항이 위법인지 따지는 데 주민번호는 한 글자도 필요 없다.

필요 없는 정보를 받지 않는 것이 가장 확실한 보호다. 암호화나 접근통제는
'가지고 있되 지키는' 방식이라 언젠가 뚫릴 수 있지만, 애초에 받지 않으면
유출될 것이 없다. 개인정보보호법이 말하는 최소수집 원칙도 같은 이야기다.

특히 주민등록번호는 고유식별정보라 법령 근거 없이는 처리 자체가 원칙적으로
금지된다. 이 서비스에는 그 근거가 없다. 그러므로 받아서는 안 된다.

이 모듈은 서버와 브라우저 양쪽에서 쓴다.
  - static/js/mask.js  전송 전에 브라우저에서 먼저 가린다 (서버가 원본을 볼 일이 없다)
  - core/mask.py       서버에서 한 번 더 가린다 (자바스크립트가 꺼진 경우 대비)

두 곳의 정규식은 같아야 한다. 바꿀 때 반드시 함께 고칠 것.
"""
import re

# 각 항목은 (이름, 정규식, 치환함수).
#
# 정규식을 느슨하게 잡으면 임금·근로시간까지 먹어 판정이 망가진다.
# 예를 들어 '2,000,000원'이나 '09:00~18:00'을 전화번호로 오인하면 안 된다.
# 그래서 자릿수와 구분자를 좁게 잡고, 아래 테스트로 회귀를 막는다.

_PATTERNS: list[tuple[str, re.Pattern, str]] = [
    # 주민등록번호 — 6자리-7자리. 뒷자리 첫 숫자는 1~4(내국인) 또는 5~8(외국인).
    # 생년월일 형식이라 앞 6자리도 어느 정도 제약이 있지만, 과하게 좁히면
    # 실제 계약서의 변형 표기를 놓치므로 뒷자리 규칙만 쓴다.
    ("주민등록번호", re.compile(r"(?<![0-9])(\d{6})\s*[-–]\s*([1-8])\d{6}(?![0-9])"),
     r"\1-\2******"),

    # 외국인등록번호도 같은 형식이라 위 패턴에 함께 걸린다.

    # 순서가 중요하다. 아래 계좌번호 패턴은 'N-N-N' 꼴을 넓게 잡으므로
    # 카드번호와 휴대전화까지 먹는다. 가려지기는 하지만 화면에 "계좌번호를 가렸습니다"
    # 라고 잘못 안내하게 된다. 좁은 패턴을 먼저 돌려 제 이름으로 잡는다.

    # 카드번호 — 4-4-4-4
    ("카드번호", re.compile(r"(?<![0-9])(\d{4})[- ](\d{4})[- ](\d{4})[- ](\d{4})(?![0-9])"),
     r"\1-****-****-****"),

    # 휴대전화 — 010/011/016/017/018/019 로 시작하는 3-4-4 또는 3-3-4
    ("전화번호", re.compile(r"(?<![0-9])(01[016-9])[-. ]?(\d{3,4})[-. ]?(\d{4})(?![0-9])"),
     r"\1-****-****"),

    # 계좌번호 — 숫자 그룹이 '-'로 2회 이상 이어지고 전체 10자리 이상.
    # 은행마다 자릿수가 달라 길이로만 잡으면 놓치거나 과잉 적중한다.
    ("계좌번호", re.compile(r"(?<![0-9-])(\d{2,6})-(\d{2,6})-(\d{2,7})(?![0-9-])"),
     r"\1-****-****"),

    # 이메일
    ("이메일", re.compile(r"(?<![\w.])([\w.+-]{1,3})[\w.+-]*@([\w-]+\.[\w.]+)"),
     r"\1***@\2"),
]


def mask(text: str) -> tuple[str, dict[str, int]]:
    """민감정보를 가린 텍스트와, 항목별로 몇 건을 가렸는지를 돌려준다.

    건수를 함께 주는 이유는 화면에 "민감정보 3건을 가리고 보냈습니다"라고
    표시하기 위해서다. 조용히 처리하면 사용자는 무슨 일이 일어났는지 모른다.
    보호는 보이게 해야 신뢰가 된다.
    """
    text = text or ""
    counts: dict[str, int] = {}
    for name, pattern, repl in _PATTERNS:
        text, n = pattern.subn(repl, text)
        if n:
            counts[name] = counts.get(name, 0) + n
    return text, counts


def summary(counts: dict[str, int]) -> str:
    """화면에 띄울 한 줄 요약."""
    if not counts:
        return ""
    parts = [f"{k} {v}건" for k, v in counts.items()]
    total = sum(counts.values())
    return f"민감정보 {total}건을 가린 뒤 검사했습니다 ({', '.join(parts)})."
