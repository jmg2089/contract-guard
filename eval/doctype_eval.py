def main() -> int:
    ok = 0
    wrong: list[str] = []

    print("=" * 78)
    print(f"{'문서':22} {'정답':11} {'판정':11} {'확신':>5}  비고")
    print("-" * 78)

    for name, expect, text in CASES:
        r = classify_document(text)
        good = r["kind"] == expect
        ok += good
        note = ""
        if r["disguise_warning"]:
            note = "위장도급 경고"
        if not good:
            note = (note + " " if note else "") + "<= 오판"
            wrong.append(f"{name}: {expect} 이어야 하는데 {r['kind']} ({r['reasons'][0][:60]})")
        print(f"{name:22} {expect:11} {r['kind']:11} {r['confidence']:>5.2f}  {note}")

    print("-" * 78)
    by: dict[str, list[int]] = {}
    for name, expect, text in CASES:
        r = classify_document(text)
        by.setdefault(expect, [0, 0])
        by[expect][1] += 1
        by[expect][0] += r["kind"] == expect
    for k, (a, b) in by.items():
        print(f"  {k:12} {a}/{b}")
    print(f"\n전체 정확도: {ok}/{len(CASES)} ({ok / len(CASES):.1%})")
    print("=" * 78)

    run_adversarial()

    if wrong:
        for w in wrong:
            print("  [오판]", w)
        return 1
    return 0


