"""마스킹 평가 — 가려야 할 것을 가리고, 가리면 안 되는 것은 건드리지 않는가.

두 번째가 더 중요하다. 정규식을 느슨하게 잡으면 임금·근로시간·날짜까지 먹어
판정이 통째로 망가진다. "2,000,000원"이 계좌번호로 보이거나 "09:00~18:00"이
전화번호로 보이면, 개인정보를 지키려다 서비스를 부순 것이 된다.

    python -m eval.mask_eval
"""
import sys

from core.mask import mask

# (입력, 가려져야 하는가, 설명)
SHOULD_MASK = [
    ("근로자 주민등록번호 : 900101-1234567", "주민등록번호", "표준 주민번호"),
    ("주민번호 900101 - 2345678 확인", "주민등록번호", "하이픈 앞뒤 공백"),
    ("외국인등록번호 950303-5123456", "주민등록번호", "외국인등록번호도 같은 형식"),
    ("급여계좌 : 국민은행 123456-01-234567", "계좌번호", "은행 계좌"),
    ("입금계좌 110-123-456789", "계좌번호", "자릿수가 다른 계좌"),
    ("카드번호 1234-5678-9012-3456", "카드번호", "카드번호"),
    ("연락처 010-1234-5678", "전화번호", "휴대전화"),
    ("전화 01012345678", "전화번호", "구분자 없는 휴대전화"),
    ("이메일 hongildong@example.com", "이메일", "이메일 주소"),
]

# 절대 건드리면 안 되는 것들. 하나라도 바뀌면 판정이 틀어진다.
MUST_NOT_CHANGE = [
    ("임금은 월 2,000,000원으로 한다.", "금액(쉼표)"),
    ("임금은 월 2000000원으로 한다.", "금액(쉼표 없음)"),
    ("시급은 10,320원으로 한다.", "시급"),
    ("위약금 3,000,000원을 배상한다.", "위약금"),
    ("근무시간은 09:00부터 18:00까지로 한다.", "근로시간"),
    ("계약기간은 2026년 3월 1일부터 2027년 2월 28일까지로 한다.", "계약기간"),
    ("계약기간 : 2026. 03. 01. ~ 2027. 02. 28.", "점으로 쓴 날짜"),
    ("1주 40시간, 1일 8시간으로 한다.", "근로시간 숫자"),
    ("연장근로는 1주 12시간을 한도로 한다.", "연장근로 한도"),
    ("통상임금의 100분의 50을 가산한다.", "가산율"),
    ("퇴직금은 30일분 이상의 평균임금으로 한다.", "퇴직금"),
    ("제17조(근로조건의 명시)", "조문 번호"),
    ("사업자등록번호 표기가 없는 문장", "일반 문장"),
    ("2025. 06. 30.~07. 31.", "교육기간 형식 날짜"),
]


def main() -> int:
    fail = []

    print("=" * 74)
    print("가려야 하는 것")
    print("-" * 74)
    for text, kind, why in SHOULD_MASK:
        out, counts = mask(text)
        ok = kind in counts
        print(f"  [{'통과' if ok else '실패'}] {why}")
        print(f"         {text}")
        print(f"      -> {out}")
        if not ok:
            fail.append(f"못 가림: {why} ({text})")

    print()
    print("=" * 74)
    print("건드리면 안 되는 것 — 여기가 더 중요하다")
    print("-" * 74)
    for text, why in MUST_NOT_CHANGE:
        out, counts = mask(text)
        ok = out == text
        print(f"  [{'통과' if ok else '실패'}] {why:20} {text}")
        if not ok:
            print(f"      -> 바뀜: {out}  {counts}")
            fail.append(f"잘못 가림: {why} -> {out}")

    print("=" * 74)
    if fail:
        for f in fail:
            print("  [실패]", f)
        return 1
    print("  전부 통과.")
    print("=" * 74)
    return 0


if __name__ == "__main__":
    sys.exit(main())
